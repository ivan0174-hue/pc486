int hid_to_set1(int usage)
{
    if (usage < 0 || usage > 255)
        return 0;
    return hid2set1[usage];
}

void hid_report_diff(HidKbdState *st, uint8_t modifiers, const uint8_t keys[6],
                     void (*emit)(void *opaque, int down, int set1), void *opaque)
{
    /* modifiers */
    uint8_t changed = st->modifiers ^ modifiers;
    for (int i = 0; i < 8; i++) {
        if (changed & (1 << i)) {
            int code = hid2set1[0xe0 + i];
            emit(opaque, (modifiers >> i) & 1, code);
        }
    }
    st->modifiers = modifiers;
    /* releases */
    for (int i = 0; i < 6; i++) {
        uint8_t k = st->keys[i];
        if (k < 4) continue;
        int still = 0;
        for (int j = 0; j < 6; j++)
            if (keys[j] == k) still = 1;
        if (!still && hid2set1[k])
            emit(opaque, 0, hid2set1[k]);
    }
    /* presses */
    for (int i = 0; i < 6; i++) {
        uint8_t k = keys[i];
        if (k < 4) continue; /* 1..3 = error/rollover */
        int was = 0;
        for (int j = 0; j < 6; j++)
            if (st->keys[j] == k) was = 1;
        if (!was && hid2set1[k])
            emit(opaque, 1, hid2set1[k]);
    }
    /* phantom state (rollover error): keep old state */
    if (keys[0] != 1)
        for (int i = 0; i < 6; i++)
            st->keys[i] = keys[i];
}
